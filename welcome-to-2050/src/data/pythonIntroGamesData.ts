export type GameType =
  | 'code_puzzle'
  | 'fill_blank'
  | 'match_code'
  | 'output_predictor'
  | 'bug_hunter'
  | 'blueprint_builder'
  | 'logic_builder'
  | 'boss_fight';

export interface GameChoiceOption {
  key: 'A' | 'B' | 'C' | 'D';
  label: string;
  isCorrect: boolean;
}

export interface LogicLine {
  id: string;
  text: string;
  correctIndex: number;
}

export interface PythonChallenge {
  id: string;
  gameId: number;
  challengeNum: number; // 1 to 10
  title: string;
  task: string;
  expectedOutput: string;
  starterCode: string;
  hint: string;
  solution: string;
  explanation: string;
  xp: number;
  // Specialized game-specific data
  puzzleTokens?: string[];
  expectedPuzzleTokens?: string[];
  blankSnippet?: string;
  blankAnswer?: string;
  matchPairs?: { left: string; right: string }[];
  matchDistractors?: string[];
  predictorChoices?: string[];
  choiceOptions?: GameChoiceOption[];
  bugCode?: string;
  bugLine?: number;
  bugType?: string;
  blueprintSpec?: string[];
  blueprintComponents?: string[];
  blueprintExpectedSlots?: string[];
  blueprintSlotsCount?: number;
  logicLines?: LogicLine[];
  bossHpDamage?: number;
  bossStrikeName?: string;
  validate?: (output: string, code: string) => { passed: boolean; message: string; diff?: string };
}

