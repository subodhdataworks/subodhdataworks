// Helper function to find lesson by topic ID or code
export function getExcelLessonById(topicIdOrCode: string | number): ExcelLessonData | undefined {
  if (typeof topicIdOrCode === 'number') {
    return EXCEL_LESSONS_DATA.find((l) => l.numericId === topicIdOrCode);
  }
  const clean = topicIdOrCode.trim();
  if (clean.startsWith('t-')) {
    const num = parseInt(clean.replace('t-', ''), 10);
    return EXCEL_LESSONS_DATA.find((l) => l.numericId === num);
  }
  if (/^\d{2}\.\d+$/.test(clean)) {
    return EXCEL_LESSONS_DATA.find((l) => l.code === clean);
  }
  const num = parseInt(clean, 10);
  if (!isNaN(num)) {
    return EXCEL_LESSONS_DATA.find((l) => l.numericId === num);
  }
  return undefined;
}
